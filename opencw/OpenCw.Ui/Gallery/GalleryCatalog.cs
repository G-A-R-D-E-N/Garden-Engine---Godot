    public static GalleryEntry Entry(GalleryId id)
    {
        foreach (var entry in Entries)
            if (entry.Id == id) return entry;
        throw new ArgumentOutOfRangeException(nameof(id), id, null);
    }

    public static bool ClosesMenusFirst(GalleryId id) => Entry(id).Category == HudCategory;
